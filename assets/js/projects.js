// Function to generate HTML for projects
function generateProjectsHTML() {
    var container = document.getElementById('projects-container');
    if (!container) return;
    
    var html = '';
    
    // Get years in descending order
    var years = Object.keys(projectsData).sort(function(a, b) { return parseInt(b) - parseInt(a); });
    
    years.forEach(function(year) {
        html += '<div class="project-year-section" data-aos="fade-up">';
        html += '<h3>' + year + '</h3>';
        html += '<div class="projects-grid">';
        
        projectsData[year].forEach(function(project) {
            html += '<div class="project-card">';
            html += '<div class="project-content">';
            html += '<h4>' + project.name + '</h4>';
            if (project.client) {
                html += '<p>' + project.client + '</p>';
            }
            html += '<div class="project-date">' + project.date + '</div>';
            html += '</div>';
            html += '</div>';
        });
        
        html += '</div>';
        html += '</div>';
    });
    
    container.innerHTML = html;
}

// Initialize when DOM is loaded
document.addEventListener('DOMContentLoaded', function() {
    generateProjectsHTML();
});